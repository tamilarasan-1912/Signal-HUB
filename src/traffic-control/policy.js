/**
 * @file City Traffic Intelligence & Control — shared constants and data-mode
 * vocabulary.
 *
 * The single most important export here is {@link DATA_MODES}. The platform
 * mixes real feeds (TomTom flow, configured CCTV, mapped ALPR infrastructure)
 * with generated ones (the signal simulator, the scenario engine, the vehicle
 * detector stub). Nothing may present generated values as measured ones, so
 * every fact that crosses a module boundary carries a mode tag taken from this
 * table. See DATA-SOURCES.md.
 *
 * Cesium-free and dependency-free on purpose: this module is imported by the
 * browser layer, the server provider and the unit tests alike.
 *
 * @module traffic-control/policy
 */

// ─── Data modes ────────────────────────────────────────────────────────────

/**
 * Provenance vocabulary for every fact the platform renders.
 *
 * - `live` — measured upstream right now (TomTom flow, a configured CCTV feed).
 * - `simulated` — generated by this platform's own simulator/scenario engine.
 * - `estimated` — derived by this platform from measured inputs (a queue
 *   inferred from a measured speed is estimated, not live).
 * - `unavailable` — a source was expected and did not answer.
 * - `unconfigured` — the capability exists but no source/key is wired up.
 *
 * @const {Object<string,string>}
 */
export const DATA_MODES = Object.freeze({
  live: 'live',
  simulated: 'simulated',
  estimated: 'estimated',
  unavailable: 'unavailable',
  unconfigured: 'unconfigured',
});

/** @const {string[]} Every mode, in presentation order. */
export const DATA_MODE_ORDER = Object.freeze([
  DATA_MODES.live,
  DATA_MODES.simulated,
  DATA_MODES.estimated,
  DATA_MODES.unavailable,
  DATA_MODES.unconfigured,
]);

const MODE_LABELS = Object.freeze({
  live: 'LIVE',
  simulated: 'SIMULATED',
  estimated: 'ESTIMATED',
  unavailable: 'UNAVAILABLE',
  unconfigured: 'UNCONFIGURED',
});

/**
 * Uppercase chip text for a composed source, e.g. `LIVE — TomTom`.
 * @param {string} mode - One of {@link DATA_MODES}.
 * @param {string} [source] - Human-readable source name.
 * @returns {string}
 */
export function dataModeLabel(mode, source) {
  const word = MODE_LABELS[mode] || 'UNKNOWN';
  return source ? `${word} — ${source}` : word;
}

/**
 * Whether a value with this mode may be described to an operator as real.
 * @param {string} mode
 * @returns {boolean}
 */
export function isMeasured(mode) {
  return mode === DATA_MODES.live;
}

