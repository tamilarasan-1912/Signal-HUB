// ─── Signal timing ─────────────────────────────────────────────────────────

/** @const {string[]} Cardinal approach directions, in phase-pair order. */
export const DIRECTIONS = Object.freeze(['N', 'S', 'E', 'W']);

/** @const {string[]} The two phase groups a 4-way intersection supports. */
export const PHASE_GROUPS = Object.freeze(['NS', 'EW']);

/**
 * Map an approach direction to its axis. Two approaches on the same axis run
 * in parallel and never conflict; approaches on different axes cross and
 * always conflict. This one function is what makes the conflict invariant
 * provable rather than asserted.
 * @param {string} direction
 * @returns {'NS'|'EW'|null}
 */
export function approachAxis(direction) {
  if (direction === 'N' || direction === 'S') return 'NS';
  if (direction === 'E' || direction === 'W') return 'EW';
  return null;
}

